impl Thresholds {
    fn active(&self) -> bool {
        self.mccabe.is_some()
            || self.cognitive.is_some()
            || self.nesting.is_some()
            || self.sloc.is_some()
            || self.abc.is_some()
            || self.returns.is_some()
            || self.aird.is_some()
            || self.aicp.is_some()
            || self.external_calls.is_some()
    }
}

/// Merges CLI thresholds (highest precedence), `knots.toml`'s per-language
/// `[<lang>.thresholds]` (next), and its global `[thresholds]` (lowest) —
/// the resolution order from `docs/unified-config-spec.md`. Resolved fresh
/// per function since the per-language layer depends on the file's language.
struct EffectiveThresholds {
    cli: Thresholds,
    global: config::TomlThresholds,
    per_language: HashMap<String, config::TomlThresholds>,
}

impl EffectiveThresholds {
    fn new(cli: Thresholds, toml_config: &Option<KnotsToml>) -> Self {
        let global = toml_config.as_ref().map(|c| c.thresholds).unwrap_or_default();
        let per_language = toml_config
            .as_ref()
            .map(|c| {
                c.languages
                    .iter()
                    .map(|(key, section)| (key.clone(), section.thresholds))
                    .collect()
            })
            .unwrap_or_default();
        Self { cli, global, per_language }
    }

    fn active(&self) -> bool {
        self.cli.active()
            || self.global.any_set()
            || self.per_language.values().any(config::TomlThresholds::any_set)
    }

    fn for_file(&self, file_path: &str) -> Thresholds {
        let lang_cfg = language_info_for_file(Path::new(file_path))
            .and_then(|info| self.per_language.get(info.key))
            .copied()
            .unwrap_or_default();
        Thresholds {
            mccabe: self.cli.mccabe.or(lang_cfg.mccabe).or(self.global.mccabe),
            cognitive: self.cli.cognitive.or(lang_cfg.cognitive).or(self.global.cognitive),
            nesting: self.cli.nesting.or(lang_cfg.nesting).or(self.global.nesting),
            sloc: self.cli.sloc.or(lang_cfg.sloc).or(self.global.sloc),
            abc: self.cli.abc.or(lang_cfg.abc).or(self.global.abc),
            returns: self.cli.returns.or(lang_cfg.returns).or(self.global.returns),
            aird: self.cli.aird.or(lang_cfg.aird).or(self.global.aird),
            aicp: self.cli.aicp.or(lang_cfg.aicp).or(self.global.aicp),
            external_calls: self
                .cli
                .external_calls
                .or(lang_cfg.external_calls)
                .or(self.global.external_calls),
        }
    }
}

/// Records a violation when `value` exceeds `limit`. In baseline mode `baseline`
/// carries this function's previously-snapshotted value for the metric; a
/// pre-existing offender that did not get *worse* (`value <= baseline`) is
/// tolerated. `baseline == None` means either "not in baseline mode" or "new
/// function not present in the baseline" — both correctly report the violation.
/// `suppressed` short-circuits the check entirely — set when a
/// `tools:suppress knots:<metric>` comment or an unqualified `tools:off`
/// region covers this function (see `knots::FunctionMetrics::suppressed`).
fn check_u32_threshold(
    out: &mut Vec<String>,
    label: &str,
    limit: Option<u32>,
    value: u32,
    baseline: Option<u32>,
    suppressed: bool,
) {
    if suppressed {
        return;
    }
    if let Some(lim) = limit {
        if value > lim {
            if let Some(base) = baseline {
                if value <= base {
                    return;
                }
            }
            out.push(format!("{} {} > {}", label, value, lim));
        }
    }
}

fn check_f64_threshold(
    out: &mut Vec<String>,
    label: &str,
    limit: Option<f64>,
    value: f64,
    baseline: Option<f64>,
    suppressed: bool,
) {
    if suppressed {
        return;
    }
    if let Some(lim) = limit {
        if value > lim {
            if let Some(base) = baseline {
                if value <= base {
                    return;
                }
            }
            out.push(format!("{} {:.2} > {:.2}", label, value, lim));
        }
    }
}


/// One function's snapshotted scores in a baseline file. Keyed on
/// `file` + `function` (line numbers are deliberately omitted so the baseline
/// stays stable as code moves). Records every gateable metric so any threshold
/// combination can be ratcheted.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct BaselineEntry {
    file: String,
    function: String,
    mccabe: u32,
    cognitive: u32,
    nesting: u32,
    sloc: u32,
    abc_magnitude: f64,
    return_count: u32,
    aird: u32,
    aicp: u32,
    external_calls: u32,
}

/// A baseline snapshot: the set of per-function scores at the time the gate was
/// adopted. On a later run, only functions that are new or worse than their
/// entry here fail the gate.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct Baseline {
    version: u32,
    functions: Vec<BaselineEntry>,
}

impl Baseline {
    fn from_file(path: &Path) -> Result<Self> {
        let content = fs::read_to_string(path)
            .with_context(|| format!("Failed to read baseline file: {}", path.display()))?;
        serde_json::from_str(&content)
            .with_context(|| format!("Failed to parse baseline file: {}", path.display()))
    }

    /// Lookup table keyed by `(file, function)`. On duplicate keys (same-named
    /// functions in one file) the last entry wins — an accepted limitation
    /// shared with clippy/eslint-style baselines.
    fn index(&self) -> HashMap<(&str, &str), &BaselineEntry> {
        self.functions
            .iter()
            .map(|e| ((e.file.as_str(), e.function.as_str()), e))
            .collect()
    }
}

/// Snapshot the analyzed functions into a Baseline, sorted by (file, function)
/// for deterministic, diff-friendly output.
fn baseline_from_metrics(metrics: &[FunctionMetrics]) -> Baseline {
    let mut functions: Vec<BaselineEntry> = metrics
        .iter()
        .map(|f| BaselineEntry {
            file: f.file_path.clone(),
            function: f.name.clone(),
            mccabe: f.mccabe,
            cognitive: f.cognitive,
            nesting: f.nesting,
            sloc: f.sloc,
            abc_magnitude: f.abc_magnitude,
            return_count: f.return_count,
            aird: f.aird,
            aicp: f.aicp,
            external_calls: f.external_calls,
        })
        .collect();
    functions.sort_by(|a, b| (&a.file, &a.function).cmp(&(&b.file, &b.function)));
    Baseline {
        version: 1,
        functions,
    }
}

fn write_baseline(path: &Path, metrics: &[FunctionMetrics]) -> Result<()> {
    let baseline = baseline_from_metrics(metrics);
    let json = serde_json::to_string_pretty(&baseline)?;
    fs::write(path, format!("{json}\n"))
        .with_context(|| format!("Failed to write baseline file: {}", path.display()))?;
    Ok(())
}

/// The set of line ranges that changed in the current working tree relative to
/// a git ref, used by `--changed` / `--since` to scope gating to touched code.
/// Keyed by canonicalized absolute path; ranges are in the *current* (post-image)
/// file so they line up with the line numbers knots reports.
struct ChangedLines {
    map: HashMap<PathBuf, Vec<(u32, u32)>>,
}

impl ChangedLines {
    /// True if `[start, end]` intersects any changed range in `file_path`.
    /// A file with no recorded changes never overlaps (its functions are skipped).
    fn overlaps(&self, file_path: &str, start: u32, end: u32) -> bool {
        let key = canonicalize_path(Path::new(file_path));
        match self.map.get(&key) {
            Some(ranges) => ranges.iter().any(|&(s, e)| start <= e && s <= end),
            None => false,
        }
    }
}

/// Canonicalize for stable map keys; fall back to the path as-given if it can't
/// be resolved (e.g. it no longer exists on disk).
fn canonicalize_path(p: &Path) -> PathBuf {
    fs::canonicalize(p).unwrap_or_else(|_| p.to_path_buf())
}

/// Run `git` with the given args, returning stdout. Errors carry git's stderr so
/// a bad ref or "not a git repository" surfaces clearly.
fn git_output(args: &[&str]) -> Result<String> {
    let out = std::process::Command::new("git")
        .args(args)
        .output()
        .context("failed to run git (is it installed and on PATH?)")?;
    if !out.status.success() {
        let stderr = String::from_utf8_lossy(&out.stderr);
        anyhow::bail!("git {} failed: {}", args.join(" "), stderr.trim());
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

/// Parse the new-file range from a unified-diff hunk header
/// (`@@ -a,b +c,d @@`), returning `(start, len)` for the `+c,d` side. `len`
/// defaults to 1 when omitted. Returns `None` if the header is malformed.
fn parse_hunk_new_range(line: &str) -> Option<(u32, u32)> {
    let plus = line.split_whitespace().find(|t| t.starts_with('+'))?;
    let mut parts = plus[1..].splitn(2, ',');
    let start: u32 = parts.next()?.parse().ok()?;
    let len: u32 = match parts.next() {
        Some(l) => l.parse().ok()?,
        None => 1,
    };
    Some((start, len))
}

/// Collect the changed line ranges of the working tree vs. `reference`. Modified
/// and added regions come from `git diff --unified=0`; brand-new untracked files
/// are treated as entirely changed so all of their functions are in scope.
fn collect_changed_lines(reference: &str) -> Result<ChangedLines> {
    let root = git_output(&["rev-parse", "--show-toplevel"])?;
    let root = PathBuf::from(root.trim());

    let diff = git_output(&["diff", "--unified=0", "--no-color", reference])?;
    let mut map: HashMap<PathBuf, Vec<(u32, u32)>> = HashMap::new();
    let mut current: Option<PathBuf> = None;

    for line in diff.lines() {
        if let Some(rest) = line.strip_prefix("+++ ") {
            // `+++ b/<path>` for the post-image; `+++ /dev/null` for a deletion
            // (nothing in the current tree to attribute, so drop scope).
            let rest = rest.split('\t').next().unwrap_or(rest);
            current = if rest == "/dev/null" {
                None
            } else {
                let rel = rest.strip_prefix("b/").unwrap_or(rest);
                Some(canonicalize_path(&root.join(rel)))
            };
        } else if line.starts_with("@@") {
            if let Some(path) = &current {
                if let Some((start, len)) = parse_hunk_new_range(line) {
                    if len > 0 {
                        map.entry(path.clone())
                            .or_default()
                            .push((start, start + len - 1));
                    }
                }
            }
        }
    }

    // Untracked files are newly added in full; cover the whole file so every
    // function counts as touched.
    let untracked = git_output(&["ls-files", "--others", "--exclude-standard"])?;
    for rel in untracked.lines() {
        if rel.is_empty() {
            continue;
        }
        map.entry(canonicalize_path(&root.join(rel)))
            .or_default()
            .push((1, u32::MAX));
    }

    Ok(ChangedLines { map })
}

fn check_thresholds(
    metrics: &[FunctionMetrics],
    t: &EffectiveThresholds,
    baseline: Option<&Baseline>,
    changed: Option<&ChangedLines>,
) -> Result<()> {
    if !t.active() {
        return Ok(());
    }

    // In baseline mode, look each function up so per-metric scores can be
    // compared against its snapshot. None for every metric when baseline is
    // off, or when the function is new (absent from the baseline).
    let index = baseline.map(|b| b.index());

    let mut output_lines: Vec<String> = Vec::new();
    let mut violation_count: usize = 0;
    // Track whether any AI metric was violated so we can append a one-line
    // pointer expanding the acronym (users meet AIRD/AICP first at the CLI).
    let mut any_aird = false;
    let mut any_aicp = false;

    for func in metrics {
        // In --changed / --since mode, only gate functions that overlap a
        // changed line range — untouched pre-existing offenders are skipped.
        if let Some(changed) = changed {
            if !changed.overlaps(&func.file_path, func.start_line, func.end_line) {
                continue;
            }
        }

        let base: Option<&BaselineEntry> = index
            .as_ref()
            .and_then(|idx| idx.get(&(func.file_path.as_str(), func.name.as_str())).copied());

        let ft = t.for_file(&func.file_path);
        let mut fv: Vec<String> = Vec::new();
        check_u32_threshold(&mut fv, "McCabe",        ft.mccabe,         func.mccabe,         base.map(|b| b.mccabe),         func.suppressed.contains("mccabe"));
        check_u32_threshold(&mut fv, "Cognitive",     ft.cognitive,      func.cognitive,      base.map(|b| b.cognitive),      func.suppressed.contains("cognitive"));
        check_u32_threshold(&mut fv, "Nesting",       ft.nesting,        func.nesting,        base.map(|b| b.nesting),        func.suppressed.contains("nesting"));
        check_u32_threshold(&mut fv, "SLOC",          ft.sloc,           func.sloc,           base.map(|b| b.sloc),           func.suppressed.contains("sloc"));
        check_f64_threshold(&mut fv, "ABC",           ft.abc,            func.abc_magnitude,  base.map(|b| b.abc_magnitude),  func.suppressed.contains("abc"));
        check_u32_threshold(&mut fv, "Returns",       ft.returns,        func.return_count,   base.map(|b| b.return_count),   func.suppressed.contains("returns"));
        check_u32_threshold(&mut fv, "AIRD",          ft.aird,           func.aird,           base.map(|b| b.aird),           func.suppressed.contains("aird"));
        check_u32_threshold(&mut fv, "AICP",          ft.aicp,           func.aicp,           base.map(|b| b.aicp),           func.suppressed.contains("aicp"));
        check_u32_threshold(&mut fv, "ExternalCalls", ft.external_calls, func.external_calls, base.map(|b| b.external_calls), func.suppressed.contains("external_calls"));

        if !fv.is_empty() {
            violation_count += 1;
            let loc = func_location(func);
            let aird_violated = fv.iter().any(|s| s.starts_with("AIRD"));
            any_aird |= aird_violated;
            any_aicp |= fv.iter().any(|s| s.starts_with("AICP"));
            let drivers_suffix = if aird_violated {
                let drivers = aird_drivers(func, 2);
                if drivers.is_empty() {
                    String::new()
                } else {
                    let parts: Vec<String> =
                        drivers.iter().map(|(l, v)| format!("{} {}", l, v)).collect();
                    format!("  (drivers: {})", parts.join(", "))
                }
            } else {
                String::new()
            };
            output_lines.push(format!("  {} — {}{}", loc, fv.join(", "), drivers_suffix));

            if aird_violated {
                output_lines.push(format_aird_breakdown(func));
                output_lines.extend(aird_tips(func));
            }
        }
    }

    if violation_count > 0 {
        if baseline.is_some() {
            eprintln!("New or worsened threshold violations vs. baseline ({violation_count}):");
        } else {
            eprintln!("Threshold violations ({violation_count}):");
        }
        for line in &output_lines {
            eprintln!("{}", line);
        }
        if let Some(pointer) = ai_metric_pointer(any_aird, any_aicp) {
            eprintln!("{}", pointer);
        }
        if baseline.is_some() {
            anyhow::bail!(
                "{} function(s) regressed beyond the baseline. Run with --write-baseline to accept the current state.",
                violation_count
            );
        }
        anyhow::bail!(
            "{} function(s) exceeded complexity thresholds",
            violation_count
        );
    }

    Ok(())
}

/// Resolve `-l`/`--language` names/extensions to the set of file extensions
/// that should be allowed during file collection.  Returns `None` when no
/// filter was requested (accept all languages).  Each token is matched
/// case-insensitively against language names first, then against extensions.
fn resolve_language_filter(names: &[String]) -> Result<Option<HashSet<&'static str>>> {
    if names.is_empty() {
        return Ok(None);
    }
    let mut allowed: HashSet<&'static str> = HashSet::new();
    for token in names {
        let lower = token.to_lowercase();
        // Try matching by language name first, then by extension.
        let lang = languages().iter().find(|l| l.name.to_lowercase() == lower).or_else(|| {
            languages().iter().find(|l| {
                l.extensions.iter().any(|e| e.to_lowercase() == lower)
                    || l.explicit_only.iter().any(|e| e.to_lowercase() == lower)
            })
        });
        match lang {
            Some(l) => {
                allowed.extend(l.extensions.iter().copied());
                allowed.extend(l.explicit_only.iter().copied());
            }
            None => anyhow::bail!(
                "Unknown language '{}'. Run `knots --supported-languages` to see valid names.",
                token
            ),
        }
    }
    Ok(Some(allowed))
}

fn configure_thread_pool(jobs: usize) {
    let n = if jobs == 0 {
        std::thread::available_parallelism().map(|n| n.get()).unwrap_or(1)
    } else {
        jobs
    };
    let _ = rayon::ThreadPoolBuilder::new().num_threads(n).build_global();
}

fn main() -> Result<()> {
    let args = Args::parse();
    configure_thread_pool(args.jobs);

    if let Some(metric) = args.explain {
        println!("{}", explain_metric(metric));
        return Ok(());
    }

    if args.supported_languages {
        print!("{}", knots::supported_languages_report());
        return Ok(());
    }

    let include_rules = args.include.as_ref().map(|p| FilterRules::from_file(p)).transpose()?;
    let exclude_rules = args.exclude.as_ref().map(|p| FilterRules::from_file(p)).transpose()?;
    let exclude_path_patterns: Vec<regex::Regex> = args
        .exclude_path
        .iter()
        .map(|p| {
            regex::Regex::new(p)
                .unwrap_or_else(|e| panic!("Invalid --exclude-path pattern '{p}': {e}"))
        })
        .collect();
    let language_filter = resolve_language_filter(&args.languages)?;

    let files = if let Some(cc) = &args.compile_commands {
        load_compile_commands(cc, &include_rules, &exclude_rules)?
    } else if !args.files.is_empty() {
        let mut collected = Vec::new();
        for path in &args.files {
            collected.extend(collect_files(
                path,
                args.recursive,
                &include_rules,
                &exclude_rules,
                &exclude_path_patterns,
                &language_filter,
            )?);
        }
        collected
    } else {
        anyhow::bail!("Either FILE or --compile-commands must be specified");
    };

    if files.is_empty() {
        return Ok(());
    }

    let cli_thresholds = Thresholds {
        mccabe: args.mccabe_threshold,
        cognitive: args.cognitive_threshold,
        nesting: args.nesting_threshold,
        sloc: args.sloc_threshold,
        abc: args.abc_threshold,
        returns: args.return_threshold,
        aird: args.aird_threshold,
        aicp: args.aicp_threshold,
        external_calls: args.external_calls_threshold,
    };
    // Optional knots.toml — walked up from cwd. All fields optional; CLI
    // flags above always win over anything loaded here.
    let knots_toml = KnotsToml::discover(&std::env::current_dir()?)?;
    let toml_exclude: Vec<config::FilterExclude> = knots_toml
        .as_ref()
        .map(|c| c.filter.exclude.clone())
        .unwrap_or_default();
    let thresholds = EffectiveThresholds::new(cli_thresholds, &knots_toml);

    // Write-baseline mode: snapshot every analyzed function and exit without
    // gating. Handled before format/mode dispatch so `--write-baseline` behaves
    // identically regardless of --format. clap's `requires` guarantees a path.
    if args.write_baseline {
        let (all_metrics, _) = collect_all_metrics(
            &files,
            &include_rules,
            &exclude_rules,
            &toml_exclude,
            args.count_anonymous_closures,
        );
        let path = args
            .baseline
            .as_ref()
            .expect("--write-baseline requires --baseline (enforced by clap)");
        write_baseline(path, &all_metrics)?;
        eprintln!(
            "Wrote baseline: {} function(s) -> {}",
            all_metrics.len(),
            path.display()
        );
        return Ok(());
    }

    let changed_ref = if args.changed { Some("HEAD") } else { args.since.as_deref() };
    let ctx = RunContext {
        thresholds,
        include_rules,
        exclude_rules,
        toml_exclude,
        baseline: args.baseline.as_ref().map(|p| Baseline::from_file(p)).transpose()?,
        changed: changed_ref.map(collect_changed_lines).transpose()?,
        count_anonymous_closures: args.count_anonymous_closures,
        verbose: args.verbose,
        quiet: args.quiet,
    };

    if args.format != OutputFormat::Text {
        return run_structured_output_mode(args.format, &files, &ctx);
    }

    if args.matrix {
        return run_matrix_mode(&files, &ctx);
    }

    if files.len() == 1 {
        return run_single_file_mode(&files[0], &ctx);
    }

    run_multi_file_mode(&files, args.report.as_deref(), &ctx)
}

fn run_structured_output_mode(
    format: OutputFormat,
    files: &[PathBuf],
    ctx: &RunContext,
) -> Result<()> {
    let (all_metrics, _) = collect_all_metrics(
        files,
        &ctx.include_rules,
        &ctx.exclude_rules,
        &ctx.toml_exclude,
        ctx.count_anonymous_closures,
    );
    match format {
        OutputFormat::Sarif => emit_sarif(&all_metrics),
        OutputFormat::Json => emit_json(&all_metrics),
        OutputFormat::Ndjson => emit_ndjson(&all_metrics),
        OutputFormat::Csv => emit_csv(&all_metrics),
        OutputFormat::Text => Ok(()),
    }
}

fn run_matrix_mode(files: &[PathBuf], ctx: &RunContext) -> Result<()> {
    let (all_metrics, skipped_files) = collect_all_metrics(
        files,
        &ctx.include_rules,
        &ctx.exclude_rules,
        &ctx.toml_exclude,
        ctx.count_anonymous_closures,
    );

    if all_metrics.is_empty() {
        anyhow::bail!("No functions found in any files (skipped {} files)", skipped_files);
    }
    if !ctx.quiet {
        display_testability_matrix(&all_metrics, files.len(), skipped_files);
    }
    check_thresholds(&all_metrics, &ctx.thresholds, ctx.baseline.as_ref(), ctx.changed.as_ref())
}

fn run_single_file_mode(file: &Path, ctx: &RunContext) -> Result<()> {
    let source_code = fs::read_to_string(file)
        .with_context(|| format!("Failed to read file: {}", file.display()))?;
    let tree = parse_file(file, &source_code)?;

    let mut metrics = collect_function_metrics(
        &tree,
        &source_code,
        file.to_str().unwrap_or(""),
        &ctx.include_rules,
        &ctx.exclude_rules,
        ctx.count_anonymous_closures,
    );
    metrics.retain(|f| !config::exclude_matches(&ctx.toml_exclude, &f.file_path, &f.name));

    if !ctx.quiet {
        analyze_code(&metrics, ctx.verbose)?;
    }
    check_thresholds(&metrics, &ctx.thresholds, ctx.baseline.as_ref(), ctx.changed.as_ref())
}

fn run_multi_file_mode(files: &[PathBuf], report: Option<&Path>, ctx: &RunContext) -> Result<()> {
    let (all_metrics, skipped_files) = collect_all_metrics(
        files,
        &ctx.include_rules,
        &ctx.exclude_rules,
        &ctx.toml_exclude,
        ctx.count_anonymous_closures,
    );

    if all_metrics.is_empty() {
        anyhow::bail!("No functions found in any files (skipped {} files)", skipped_files);
    }
    if let Some(report_path) = report {
        write_detailed_report(&all_metrics, ctx.verbose, report_path)?;
    }
    if !ctx.quiet {
        display_recursive_summary(&all_metrics, files.len(), skipped_files, report);
    }
    check_thresholds(&all_metrics, &ctx.thresholds, ctx.baseline.as_ref(), ctx.changed.as_ref())
}

/// Load file paths from compile_commands.json
fn load_compile_commands(
    compile_commands_path: &Path,
    include_rules: &Option<FilterRules>,
    exclude_rules: &Option<FilterRules>,
) -> Result<Vec<PathBuf>> {
    let content = fs::read_to_string(compile_commands_path).with_context(|| {
        format!(
            "Failed to read compile_commands.json: {}",
            compile_commands_path.display()
        )
    })?;

    let commands: Vec<CompileCommand> = serde_json::from_str(&content).with_context(|| {
        format!(
            "Failed to parse compile_commands.json: {}",
            compile_commands_path.display()
        )
    })?;

    let mut files = Vec::new();

    for cmd in commands {
        let file_path = PathBuf::from(&cmd.file);

        // Only process supported source files
        if let Some(ext) = file_path.extension() {
            if is_source_extension(ext) {
                let file_str = file_path.to_string_lossy();
                if should_process_file(&file_str, include_rules, exclude_rules) {
                    // Use absolute path if available, otherwise relative
                    if file_path.is_absolute() {
                        files.push(file_path);
                    } else {
                        // Try to make it absolute using the directory from compile command
                        let abs_path = if !cmd.directory.is_empty() {
                            PathBuf::from(&cmd.directory).join(&file_path)
                        } else {
                            file_path.clone()
                        };

                        if abs_path.exists() {
                            files.push(abs_path);
                        } else if file_path.exists() {
                            files.push(file_path);
                        }
                    }
                }
            }
        }
    }

    if files.is_empty() {
        anyhow::bail!("No supported source files found in compile_commands.json");
    }

    Ok(files)
}

/// Collect files to process based on the path and recursive flag
fn collect_files(
    path: &PathBuf,
    recursive: bool,
    include_rules: &Option<FilterRules>,
    exclude_rules: &Option<FilterRules>,
    exclude_path_patterns: &[regex::Regex],
    language_filter: &Option<HashSet<&'static str>>,
) -> Result<Vec<PathBuf>> {
    let mut files = Vec::new();

    let ext_allowed = |ext: &std::ffi::OsStr| -> bool {
        language_filter.as_ref().map_or(true, |set| {
            ext.to_str().map(|e| set.contains(e)).unwrap_or(false)
        })
    };

    if path.is_file() {
        // Single file mode — accepts explicit-only extensions (e.g. .f, .h) in addition to
        // recursive-discovery extensions. is_parseable_extension covers both sets.
        let ext = path.extension();
        let supported = ext.map(|e| is_parseable_extension(e)).unwrap_or(false);
        if !supported || !ext.map(ext_allowed).unwrap_or(false) {
            return Ok(files);
        }
        let file_str = path.to_string_lossy();
        if !path_is_excluded(&file_str, exclude_path_patterns)
            && should_process_file(&file_str, include_rules, exclude_rules)
        {
            files.push(path.clone());
        }
    } else if path.is_dir() {
        if !recursive {
            anyhow::bail!(
                "Path '{}' is a directory. Use -r/--recursive to process directories recursively.",
                path.display()
            );
        }

        // Recursive directory mode - scan source files, respecting .gitignore
        for entry in WalkBuilder::new(path)
            .follow_links(true)
            .build()
            .filter_map(|e| e.ok())
        {
            let file_path = entry.path();
            if file_path.is_file() {
                if let Some(ext) = file_path.extension() {
                    if is_source_extension(ext) && ext_allowed(ext) {
                        let file_str = file_path.to_string_lossy();
                        if !path_is_excluded(&file_str, exclude_path_patterns)
                            && should_process_file(&file_str, include_rules, exclude_rules)
                        {
                            files.push(file_path.to_path_buf());
                        }
                    }
                }
            }
        }

        if files.is_empty() {
            anyhow::bail!(
                "No supported source files found in directory: {}",
                path.display()
            );
        }
    } else {
        anyhow::bail!("Path '{}' does not exist", path.display());
    }

    Ok(files)
}

fn path_is_excluded(path: &str, patterns: &[regex::Regex]) -> bool {
    patterns.iter().any(|re| re.is_match(path))
}

/// Check if a file should be processed based on include/exclude rules
fn should_process_file(
    file_path: &str,
    include_rules: &Option<FilterRules>,
    exclude_rules: &Option<FilterRules>,
) -> bool {
    // Check include rules first (whitelist)
    if let Some(rules) = include_rules {
        if !rules.matches_file(file_path) {
            return false;
        }
    }

    // Check exclude rules (blacklist) - if it matches exclude, DON'T process
    if let Some(rules) = exclude_rules {
        if rules.matches_file(file_path) {
            return false;
        }
    }

    true
}

/// Collect function metrics from a file


/// Collect FunctionMetrics across multiple files, skipping unreadable/unparseable ones.
/// Returns (metrics, skipped_file_count). Used by SARIF mode.
fn collect_all_metrics(
    files: &[PathBuf],
    include_rules: &Option<FilterRules>,
    exclude_rules: &Option<FilterRules>,
    toml_exclude: &[config::FilterExclude],
    count_anonymous_closures: bool,
) -> (Vec<FunctionMetrics>, usize) {
    let skipped = AtomicUsize::new(0);
    let mut all_metrics: Vec<FunctionMetrics> = files
        .par_iter()
        .flat_map(|file| {
            let source_code = match fs::read_to_string(file) {
                Ok(c) => c,
                Err(e) => {
                    eprintln!("Warning: Skipping {}: {}", file.display(), e);
                    skipped.fetch_add(1, Ordering::Relaxed);
                    return Vec::new();
                }
            };
            let tree = match parse_file(file, &source_code) {
                Ok(t) => t,
                Err(_) => {
                    let hint = if file.extension().and_then(|e| e.to_str()) == Some("h") {
                        " (if this file contains C++, rename to .hpp)"
                    } else {
                        ""
                    };
                    eprintln!("Warning: Failed to parse {}{}", file.display(), hint);
                    skipped.fetch_add(1, Ordering::Relaxed);
                    return Vec::new();
                }
            };
            collect_function_metrics(
                &tree,
                &source_code,
                file.to_str().unwrap_or(""),
                include_rules,
                exclude_rules,
                count_anonymous_closures,
            )
        })
        .collect();
    all_metrics.retain(|f| !config::exclude_matches(toml_exclude, &f.file_path, &f.name));
    all_metrics.sort_by(|a, b| a.file_path.cmp(&b.file_path).then(a.name.cmp(&b.name)));
    (all_metrics, skipped.load(Ordering::Relaxed))
}



